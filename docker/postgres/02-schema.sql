BEGIN;

SET LOCAL ROLE album_app;

CREATE TABLE public.users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(32) NOT NULL UNIQUE,
    email varchar(254) NOT NULL,
    password_hash text NOT NULL,
    role varchar(16) NOT NULL CHECK (role IN ('member', 'admin')),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE
);

CREATE TABLE public.albums (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id integer NOT NULL REFERENCES public.users (id),
    category_id integer NOT NULL REFERENCES public.categories (id) ON DELETE RESTRICT,
    name varchar(100) NOT NULL,
    visibility varchar(7) NOT NULL CHECK (visibility IN ('public', 'private')),
    version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.photos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id integer NOT NULL REFERENCES public.albums (id),
    uploader_id integer NOT NULL REFERENCES public.users (id),
    original_path text NOT NULL,
    thumbnail_path text NOT NULL,
    upload_id uuid NOT NULL,
    media_type varchar(32) NOT NULL,
    size_bytes integer NOT NULL CHECK (size_bytes BETWEEN 1 AND 10000000),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT photos_album_uploader_upload_key UNIQUE (album_id, uploader_id, upload_id)
);

CREATE TABLE public.comments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo_id integer NOT NULL REFERENCES public.photos (id),
    user_id integer NOT NULL REFERENCES public.users (id),
    body varchar(200) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.photo_likes (
    user_id integer NOT NULL REFERENCES public.users (id),
    photo_id integer NOT NULL REFERENCES public.photos (id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, photo_id)
);

CREATE INDEX albums_owner_id_id_idx ON public.albums (owner_id, id DESC);
CREATE INDEX albums_category_id_idx ON public.albums (category_id);
CREATE INDEX photos_album_id_id_idx ON public.photos (album_id, id DESC);
CREATE INDEX comments_photo_id_created_at_id_idx ON public.comments (photo_id, created_at DESC, id DESC);
CREATE INDEX photo_likes_photo_id_idx ON public.photo_likes (photo_id);

COMMIT;
